"""Bundle every generated result into a single LaTeX file for the paper.

    python experiments/run_all.py
    python experiments/export_results_tex.py      # -> paper/generated/results.tex

The bundle defines the numeric macros produced by run_all.py, one macro per
table body (\\TabFeatures, \\TabAbstraction, ...) and one pgfplots table per
figure (\\DatParetoChurn, ...), so that a manuscript can be compiled from a
single self-contained file (e.g. on Overleaf) while every number still comes
from the experiment script.
"""
from __future__ import annotations

from pathlib import Path

GEN = Path(__file__).resolve().parents[1] / "paper" / "generated"

TABLES = {
    "TabFeatures": "tab_features.tex",
    "TabAbstraction": "tab_abstraction.tex",
    "TabPlacement": "tab_placement.tex",
    "TabDynamic": "tab_dynamic.tex",
    "TabAblation": "tab_ablation.tex",
    "TabBaselines": "tab_baselines.tex",
    "TabRobustness": "tab_robustness.tex",
}
DATA = {
    "DatParetoChurn": "fig_pareto_churn.dat",
    "DatParetoRetail": "fig_pareto_retail.dat",
    "DatTraceB": "fig_trace_B.dat",
}


def main() -> None:
    out = ["% Generated by experiments/export_results_tex.py from the outputs of run_all.py. Do not edit.",
           "% Requires \\usepackage{pgfplotstable} in the preamble.", ""]
    out.append((GEN / "macros.tex").read_text().strip())
    out.append("")
    for name, fname in TABLES.items():
        body = (GEN / fname).read_text().strip()
        out.append(f"\\newcommand{{\\{name}}}{{%\n{body}\n}}")
    out.append("")
    for name, fname in DATA.items():
        out.append(f"\\pgfplotstableread{{\n{(GEN / fname).read_text().strip()}\n}}\\{name}")
    locs = (GEN / "fig_trace_B_locations.txt").read_text().split()
    for j, loc in enumerate(locs):
        out.append(f"\\newcommand{{\\TraceLoc{'ABCDEFGH'[j]}}}{{{loc}}}")
    (GEN / "results.tex").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {GEN / 'results.tex'}")


if __name__ == "__main__":
    main()
